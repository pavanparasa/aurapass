//! Application-level configuration.
//!
//! This is the *only* thing AuraPass stores in the clear: a list of vault
//! paths, UI preferences and the browser-bridge pairing token. Vault contents
//! never live here.
//!
//! Locations follow the XDG base-directory spec (via the `directories` crate):
//!
//! * config → `~/.config/aurapass/config.json`
//! * data → `~/.local/share/aurapass/`
//!
//! Set `AURAPASS_CONFIG_DIR` to relocate everything, which is what the test
//! suite and portable installs do.

use crate::crypto::{random_bytes, Key};
use crate::error::{Error, Result};
use crate::pin::PinUnlock;
use crate::util::{atomic_write, b64url_encode};
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

/// Version of the config file layout.
pub const CONFIG_VERSION: u32 = 1;

/// Environment variable that overrides the config directory.
pub const CONFIG_DIR_ENV: &str = "AURAPASS_CONFIG_DIR";

/// A vault the user has opened before.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct VaultRef {
    /// Path to the `.aurapass` file.
    pub path: PathBuf,
    /// Cached display name, so the unlock list renders before any file read.
    pub name: String,
    /// When it was last unlocked.
    #[serde(default)]
    pub last_opened: Option<DateTime<Utc>>,
    /// Whether it shows on the unlock screen.
    #[serde(default = "yes")]
    pub pinned: bool,
}

fn yes() -> bool {
    true
}

impl VaultRef {
    /// Remember a vault at `path`.
    pub fn new(path: impl Into<PathBuf>, name: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            name: name.into(),
            last_opened: None,
            pinned: true,
        }
    }
}

/// Settings for the localhost bridge the browser extension talks to.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct BridgeConfig {
    /// Whether to run the bridge at all.
    #[serde(default = "yes")]
    pub enabled: bool,
    /// Preferred TCP port. The bridge falls back to an ephemeral port if busy.
    #[serde(default = "default_port")]
    pub port: u16,
    /// Pairing token; the extension must present this to talk to the vault.
    #[serde(default)]
    pub token: String,
    /// Require the desktop app to be running (no headless unlocking).
    #[serde(default = "yes")]
    pub require_gui: bool,
    /// Lock the vault when the last extension disconnects.
    #[serde(default)]
    pub lock_on_disconnect: bool,
    /// Browsers the user has approved. Each one carries the secret it was
    /// issued when the user clicked "Allow", so no token is ever typed by hand.
    #[serde(default)]
    pub paired: Vec<PairedBrowser>,
}

/// A browser extension that the user has approved.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct PairedBrowser {
    /// Stable id generated by the extension and kept in its own storage.
    #[serde(default)]
    pub id: String,
    /// Display name, e.g. `Chrome`.
    #[serde(default)]
    pub name: String,
    /// The secret the app issued. Only the app and that browser know it.
    #[serde(default)]
    pub token: String,
    /// When the pairing happened, for the settings list.
    #[serde(default)]
    pub paired_at: String,
}

fn default_port() -> u16 {
    crate::DEFAULT_BRIDGE_PORT
}

impl Default for BridgeConfig {
    fn default() -> Self {
        Self {
            enabled: true,
            port: crate::DEFAULT_BRIDGE_PORT,
            token: new_bridge_token(),
            require_gui: true,
            lock_on_disconnect: false,
            paired: Vec::new(),
        }
    }
}

impl BridgeConfig {
    /// Replace the pairing token with a fresh one.
    pub fn rotate_token(&mut self) {
        self.token = new_bridge_token();
    }

    /// `127.0.0.1:port` for display.
    pub fn address(&self) -> String {
        format!("127.0.0.1:{}", self.port)
    }

    /// The token as a [`Key`], for the encrypted bridge channel.
    pub fn session_key(&self, salt: &[u8]) -> Result<Key> {
        if self.token.is_empty() {
            return Err(Error::other("the bridge has no pairing token"));
        }
        let key = Key::from_slice(&crate::crypto::sha256(self.token.as_bytes()))?;
        key.subkey(b"aurapass/v2/bridge-session", salt)
    }
}

/// Generate a fresh, URL-safe pairing token.
pub fn new_bridge_token() -> String {
    b64url_encode(random_bytes::<32>())
}

/// Remembered window geometry.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct WindowState {
    /// Width in logical pixels.
    pub width: f32,
    /// Height in logical pixels.
    pub height: f32,
    /// Whether the window was maximised.
    #[serde(default)]
    pub maximized: bool,
}

impl Default for WindowState {
    fn default() -> Self {
        Self {
            width: 1180.0,
            height: 760.0,
            maximized: false,
        }
    }
}

/// The whole configuration file.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct AppConfig {
    /// Layout version.
    #[serde(default = "config_version")]
    pub version: u32,
    /// Known vaults.
    #[serde(default)]
    pub vaults: Vec<VaultRef>,
    /// Browser bridge settings.
    #[serde(default)]
    pub bridge: BridgeConfig,
    /// `"system"`, `"dark"` or `"light"`.
    #[serde(default = "system_theme")]
    pub theme: String,
    /// Remembered window geometry.
    #[serde(default)]
    pub window: WindowState,
    /// Whether the first-run experience has been completed.
    #[serde(default)]
    pub onboarded: bool,
    /// Where import/export dialogs last pointed.
    #[serde(default)]
    pub last_directory: Option<PathBuf>,
    /// Show a system-tray icon.
    #[serde(default = "yes")]
    pub tray_enabled: bool,
    /// Hide to the tray instead of quitting when the window is closed.
    #[serde(default = "yes")]
    pub close_to_tray: bool,
    /// Use a dark tray glyph (readable on light panels). The default is a light
    /// glyph, which is what Ubuntu's dark top bar needs.
    #[serde(default)]
    pub tray_icon_dark: bool,
    /// Open AuraPass automatically when the user logs in.
    #[serde(default)]
    pub autostart: bool,
    /// Master keys wrapped under an unlock PIN, one per vault, valid only for
    /// the desktop session that issued them.
    #[serde(default)]
    pub pin_unlocks: Vec<PinUnlock>,
}

fn config_version() -> u32 {
    CONFIG_VERSION
}

fn system_theme() -> String {
    "system".to_string()
}

impl Default for AppConfig {
    fn default() -> Self {
        Self {
            version: CONFIG_VERSION,
            vaults: Vec::new(),
            bridge: BridgeConfig::default(),
            theme: system_theme(),
            window: WindowState::default(),
            onboarded: false,
            last_directory: None,
            tray_enabled: true,
            close_to_tray: true,
            tray_icon_dark: false,
            autostart: false,
            pin_unlocks: Vec::new(),
        }
    }
}

impl AppConfig {
    /// `$AURAPASS_CONFIG_DIR` or `~/.config/aurapass`.
    pub fn config_dir() -> PathBuf {
        if let Ok(dir) = std::env::var(CONFIG_DIR_ENV)
            && !dir.trim().is_empty()
        {
            return PathBuf::from(dir);
        }
        directories::ProjectDirs::from("io", "aurapass", "aurapass")
            .map(|p| p.config_dir().to_path_buf())
            .unwrap_or_else(|| PathBuf::from(".aurapass"))
    }

    /// Where config.json lives.
    pub fn path() -> PathBuf {
        Self::path_in(&Self::config_dir())
    }

    /// Path of the config file inside a specific directory.
    pub fn path_in(dir: &Path) -> PathBuf {
        dir.join("config.json")
    }

    /// Directory for logs, exports and caches.
    pub fn data_dir() -> PathBuf {
        if let Ok(dir) = std::env::var(CONFIG_DIR_ENV)
            && !dir.trim().is_empty()
        {
            return PathBuf::from(dir).join("data");
        }
        directories::ProjectDirs::from("io", "aurapass", "aurapass")
            .map(|p| p.data_dir().to_path_buf())
            .unwrap_or_else(|| PathBuf::from(".aurapass/data"))
    }

    /// Runtime directory for the bridge socket/lock file.
    pub fn runtime_dir() -> PathBuf {
        if let Ok(dir) = std::env::var("XDG_RUNTIME_DIR")
            && !dir.trim().is_empty()
        {
            return PathBuf::from(dir).join("aurapass");
        }
        Self::data_dir().join("run")
    }

    /// Suggested location for a brand-new vault: `~/AuraPass/<name>.aurapass`.
    pub fn suggested_vault_path(name: &str) -> PathBuf {
        let slug: String = name
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                    c
                } else {
                    '-'
                }
            })
            .collect();
        let slug = slug.trim_matches('-').to_ascii_lowercase();
        let slug = if slug.is_empty() {
            "vault".to_string()
        } else {
            slug
        };
        let home = directories::UserDirs::new()
            .map(|u| u.home_dir().to_path_buf())
            .unwrap_or_else(|| PathBuf::from("."));
        home.join("AuraPass").join(format!("{slug}.aurapass"))
    }

    /// Load the config, falling back to defaults when the file is missing.
    ///
    /// A corrupt config is *not* fatal: it is moved aside and defaults are
    /// returned, because being unable to start is worse than losing prefs.
    pub fn load() -> Self {
        Self::load_from(&Self::config_dir())
    }

    /// Load from an explicit directory. Used by tests and by portable mode.
    pub fn load_from(dir: &Path) -> Self {
        let path = Self::path_in(dir);
        let Ok(text) = std::fs::read_to_string(&path) else {
            return Self::default();
        };
        match serde_json::from_str::<AppConfig>(&text) {
            Ok(config) => config,
            Err(e) => {
                let backup = path.with_extension(format!("corrupt-{}.json", crate::now_unix()));
                let _ = std::fs::rename(&path, &backup);
                eprintln!(
                    "aurapass: config.json was unreadable ({e}); moved to {} and starting fresh",
                    backup.display()
                );
                Self::default()
            }
        }
    }

    /// Persist the config with owner-only permissions.
    pub fn save(&self) -> Result<()> {
        self.save_to_dir(&Self::config_dir())
    }

    /// Persist into an explicit directory.
    pub fn save_to_dir(&self, dir: &Path) -> Result<()> {
        let body = serde_json::to_vec_pretty(self)?;
        atomic_write(&Self::path_in(dir), &body, 0o600)
    }

    /// Insert or update a vault reference and return it.
    pub fn remember_vault(&mut self, path: impl Into<PathBuf>, name: impl Into<String>) -> &VaultRef {
        let path = path.into();
        if let Some(index) = self.vaults.iter().position(|v| v.path == path) {
            self.vaults[index].name = name.into();
            self.vaults[index].last_opened = Some(Utc::now());
            let idx = index;
            return &self.vaults[idx];
        }
        self.vaults.push(VaultRef {
            path,
            name: name.into(),
            last_opened: Some(Utc::now()),
            pinned: true,
        });
        self.vaults
            .last()
            .expect("just pushed a vault reference")
    }

    /// Forget a vault, along with any PIN issued for it.
    pub fn forget_vault(&mut self, path: &Path) {
        self.vaults.retain(|v| v.path != path);
        self.pin_unlocks.retain(|pin| pin.vault != path);
    }

    /// The PIN envelope for `path`, if any.
    pub fn pin_for(&self, path: &Path) -> Option<&PinUnlock> {
        self.pin_unlocks.iter().find(|pin| pin.vault == path)
    }

    /// Insert or replace the PIN envelope for a vault.
    pub fn set_pin(&mut self, pin: PinUnlock) {
        self.pin_unlocks.retain(|existing| existing.vault != pin.vault);
        self.pin_unlocks.push(pin);
    }

    /// Drop the PIN envelope for a vault.
    pub fn remove_pin(&mut self, path: &Path) {
        self.pin_unlocks.retain(|pin| pin.vault != path);
    }

    /// Vaults that should be listed on the unlock screen, most recent first.
    pub fn pinned_vaults(&self) -> Vec<&VaultRef> {
        let mut refs: Vec<&VaultRef> = self.vaults.iter().filter(|v| v.pinned).collect();
        refs.sort_by(|a, b| b.last_opened.cmp(&a.last_opened));
        refs
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roundtrip_through_disk() {
        let dir = tempfile::tempdir().unwrap();

        let mut config = AppConfig::default();
        config.remember_vault("/tmp/example.aurapass", "Example");
        config.bridge.port = 9123;
        config.autostart = true;
        config.save_to_dir(dir.path()).unwrap();

        let loaded = AppConfig::load_from(dir.path());
        assert_eq!(loaded.vaults.len(), 1);
        assert_eq!(loaded.vaults[0].name, "Example");
        assert_eq!(loaded.bridge.port, 9123);
        assert!(loaded.autostart);
        assert_eq!(loaded.bridge.token.len(), 43, "32 bytes of base64url");
    }

    #[test]
    fn config_file_is_owner_only() {
        use std::os::unix::fs::PermissionsExt as _;
        let dir = tempfile::tempdir().unwrap();
        AppConfig::default().save_to_dir(dir.path()).unwrap();
        let mode = std::fs::metadata(AppConfig::path_in(dir.path()))
            .unwrap()
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(mode, 0o600);
    }

    #[test]
    fn missing_config_is_not_an_error() {
        let dir = tempfile::tempdir().unwrap();
        let config = AppConfig::load_from(&dir.path().join("does-not-exist"));
        assert!(config.vaults.is_empty());
        assert!(!config.bridge.token.is_empty());
    }

    #[test]
    fn corrupt_config_is_moved_aside() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(AppConfig::path_in(dir.path()), "{not json").unwrap();

        let config = AppConfig::load_from(dir.path());
        assert!(config.vaults.is_empty());
        let leftovers: Vec<_> = std::fs::read_dir(dir.path())
            .unwrap()
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().to_string())
            .filter(|n| n.contains("corrupt"))
            .collect();
        assert_eq!(leftovers.len(), 1, "the bad file should be preserved");
    }

    #[test]
    fn tokens_are_unique_and_url_safe() {
        let a = new_bridge_token();
        let b = new_bridge_token();
        assert_ne!(a, b);
        assert!(
            a.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        );
        assert_eq!(a.len(), 43);
    }

    #[test]
    fn tokens_can_be_rotated() {
        let mut bridge = BridgeConfig::default();
        let first = bridge.token.clone();
        bridge.rotate_token();
        assert_ne!(first, bridge.token);
    }

    #[test]
    fn remembering_a_vault_twice_updates_in_place() {
        let mut config = AppConfig::default();
        config.remember_vault("/tmp/a.aurapass", "First");
        config.remember_vault("/tmp/a.aurapass", "Renamed");
        assert_eq!(config.vaults.len(), 1);
        assert_eq!(config.vaults[0].name, "Renamed");
    }

    #[test]
    fn forgetting_a_vault_removes_it() {
        let mut config = AppConfig::default();
        config.remember_vault("/tmp/a.aurapass", "A");
        config.remember_vault("/tmp/b.aurapass", "B");
        config.forget_vault(Path::new("/tmp/a.aurapass"));
        assert_eq!(config.vaults.len(), 1);
        assert_eq!(config.vaults[0].name, "B");
    }

    #[test]
    fn session_key_needs_a_token() {
        let mut bridge = BridgeConfig::default();
        assert!(bridge.session_key(b"salt").is_ok());
        bridge.token.clear();
        assert!(bridge.session_key(b"salt").is_err());
    }

    #[test]
    fn suggested_paths_are_slugified_and_stay_at_home() {
        let p = AppConfig::suggested_vault_path("My Personal Vault!");
        let name = p.file_name().unwrap().to_string_lossy().to_string();
        assert_eq!(name, "my-personal-vault.aurapass");
        assert_eq!(AppConfig::suggested_vault_path("").file_name().unwrap(), "vault.aurapass");
    }
}
